"""Training entry point for the Phase 4 crop‑recommendation model.

The script is deliberately lightweight – it loads the processed training split
generated by ``prepare_training_data.py``, fits the placeholder model from
``backend.ml.crop_recommendation`` and persists both the model and a
sample recommendation CSV.

Execution::

    python train_crop_recommendation.py

The script uses the ``Settings`` object from ``backend.core.config`` to
derive the absolute model directory (``MODEL_DIR``). If that attribute does not
exist we fall back to ``models`` under the repository root, mirroring the other
training utilities.
"""

from __future__ import annotations

import os
import json
from pathlib import Path

import joblib
import pandas as pd

from backend.core.config import get_settings
from ml.inference.crop_recommendation import merge_data, train_model, recommend

# ---------------------------------------------------------------------------
# Resolve directories
# ---------------------------------------------------------------------------
BASE_DIR = Path(r"c:\Users\USER\Downloads\FinalYearProject")
TRAIN_DIR = BASE_DIR / "training_data"
# Model directory – use config if present, otherwise default to ``models``.
settings = get_settings()
MODEL_DIR = Path(getattr(settings, "MODEL_DIR", "models"))
MODEL_DIR.mkdir(parents=True, exist_ok=True)

def main() -> None:
    # 1️⃣ Load and merge data
    X, y = merge_data()

    # 2️⃣ Train the model
    model = train_model(X, y)

    # 3️⃣ Persist the trained model
    model_path = MODEL_DIR / "crop_recommendation_model.pkl"
    joblib.dump(model, model_path)
    print(f"Model saved to {model_path}")

    # 4️⃣ Generate a dummy recommendation CSV for the *test* split (if present).
    #    This provides a tangible artefact for downstream pipelines.
    test_path = TRAIN_DIR / "crop_recommendation_test.csv"
    if test_path.is_file():
        test_df = pd.read_csv(test_path)
        # Use the first ``top_k`` predictions for each row as a simple demo.
        records = []
        for _, row in test_df.iterrows():
            # Drop the target column if it exists – the model expects only the
            # feature set.
            row_features = row.drop(labels=["label_encoded", "label"], errors="ignore").to_dict()
            recs = recommend(row_features, top_k=5)
            for r in recs:
                records.append(
                    {
                        "district_id": row.get("district_id", None),
                        "rainfall_mm": row.get("rainfall", None),
                        "crop_name": r["crop_name"],
                        "confidence": r["confidence"],
                    }
                )
        out_df = pd.DataFrame(records)
        out_csv = TRAIN_DIR / "crop_recommendations.csv"
        out_df.to_csv(out_csv, index=False)
        print(f"Recommendation CSV written to {out_csv}")
    else:
        print("No test split found – only the model artifact was generated.")

    # 5️⃣ Optionally record the output path in a small JSON metadata file so
    #    ``prepare_training_data.py`` can read it back.
    meta = {"crop_recommendation_output": str(TRAIN_DIR / "crop_recommendations.csv")}
    meta_path = TRAIN_DIR / "crop_recommendation_metadata.json"
    meta_path.write_text(json.dumps(meta, indent=2))


if __name__ == "__main__":
    main()

