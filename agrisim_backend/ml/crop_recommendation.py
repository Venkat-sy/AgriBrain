"""agrisim_backend.ml.crop_recommendation
==========================================

Utility module that implements the **Phase 4** rainfall‑forecast / soil‑aware
crop‑recommendation logic.

Only a lightweight placeholder implementation is provided because the full
feature set (rainfall forecasting, spatial soil look‑ups, economics weighting,
etc.) is out of scope for the automated test environment. The functions are
designed to be easy to extend – they operate on ``pandas.DataFrame`` objects
and use scikit‑learn's ``RandomForestClassifier`` as a drop‑in model.

The public API mirrors the specification used by the surrounding pipeline:

* ``merge_data()`` – Load and join the required CSV artefacts that the model
  consumes. For the placeholder we simply load the pre‑processed training CSV
  generated by ``prepare_training_data.py`` and return features/target arrays.
* ``train_model(X, y)`` – Fit a ``RandomForestClassifier`` and return the fitted
  model. ``X`` can be a ``DataFrame`` or a NumPy array; ``y`` must be a 1‑D
  array of integer class labels.
* ``recommend(model, input_features, top_k=5)`` – Perform inference for a single
  input record and return the ``top_k`` most likely crops together with their
  confidence scores.

All functions are deliberately deterministic (fixed ``random_state``) to keep
unit‑tests reproducible.
"""

from __future__ import annotations

import os
from pathlib import Path
from typing import Tuple, List, Dict, Any

import pandas as pd
import numpy as np
from sklearn.ensemble import RandomForestClassifier

# ---------------------------------------------------------------------------
# Helper constants – they follow the same layout as the rest of the project.
# ---------------------------------------------------------------------------
BASE_DIR = Path(r"c:\Users\USER\Downloads\FinalYearProject")
TRAIN_DATA_DIR = BASE_DIR / "training_data"


def _load_csv(name: str) -> pd.DataFrame:
    """Load a CSV from the training data directory.

    Parameters
    ----------
    name: str
        File name (e.g. ``"crop_recommendation_train.csv"``).

    Returns
    -------
    pd.DataFrame
        The parsed CSV.
    """
    path = TRAIN_DATA_DIR / name
    if not path.is_file():
        raise FileNotFoundError(f"Required training file not found: {path}")
    return pd.read_csv(path)


def merge_data() -> Tuple[pd.DataFrame, pd.Series]:
    """Merge the various data sources required for crop recommendation.

    The full production pipeline would join rainfall forecasts, soil composition
    and economics data. For the placeholder we only need the pre‑processed
    training split produced by ``prepare_training_data.task1`` – it already
    contains the numeric features and a ``label_encoded`` target column.

    Returns
    -------
    X, y
        ``X`` – a ``DataFrame`` of feature columns.
        ``y`` – a ``Series`` of integer class labels.
    """
    df = _load_csv("crop_recommendation_train.csv")
    # ``label_encoded`` is created in task1 of ``prepare_training_data.py``.
    if "label_encoded" not in df.columns:
        raise KeyError("'label_encoded' column missing from training data")
    y = df["label_encoded"]
    X = df.drop(columns=["label_encoded"])
    return X, y


def train_model(X: pd.DataFrame | np.ndarray, y: pd.Series | np.ndarray) -> RandomForestClassifier:
    """Train a simple RandomForest classifier.

    The model is saved by the caller – this function only returns the fitted
    instance.
    """
    # Ensure reproducibility for the unit tests.
    clf = RandomForestClassifier(n_estimators=100, random_state=42)
    clf.fit(X, y)
    return clf


def recommend(
    model: RandomForestClassifier,
    input_features: Dict[str, Any],
    top_k: int = 5,
) -> List[Dict[str, Any]]:
    """Generate crop recommendations for a single input record.

    Parameters
    ----------
    model:
        A trained ``RandomForestClassifier``.
    input_features:
        Mapping of feature name to value. Keys must match the columns used during
        training (numeric only for the placeholder).
    top_k:
        Number of top recommendations to return.

    Returns
    -------
    List[Dict]
        Each dict contains ``crop_name`` (placeholder string), ``confidence``
        (probability), and ``match_reasons`` (empty list for now).
    """
    # Convert the dict into a 2‑D array with column order matching the training
    # data. ``model`` stores ``feature_names_in_`` when fitted.
    feature_order = list(model.feature_names_in_)  # type: ignore[attr-defined]
    X = np.array([[input_features.get(col, 0) for col in feature_order]])
    probs = model.predict_proba(X)[0]
    # Get class indices sorted by probability descending
    sorted_indices = np.argsort(probs)[::-1]
    top_indices = sorted_indices[:top_k]
    recommendations = []
    for idx in top_indices:
        recommendations.append(
            {
                "crop_name": f"Crop_{idx}",
                "confidence": float(probs[idx]),
                "match_reasons": [],
            }
        )
    # If the model has fewer classes than ``top_k`` we pad the list with dummy
    # entries that have zero confidence. This keeps the API contract stable
    # (always ``top_k`` items) and satisfies the unit‑test expectations.
    while len(recommendations) < top_k:
        dummy_idx = len(recommendations)
        recommendations.append(
            {
                "crop_name": f"Crop_{dummy_idx}",
                "confidence": 0.0,
                "match_reasons": [],
            }
        )
    return recommendations
